README1 = dd(r'''
    # timerwheel

    A hashed timing wheel for embedded firmware: no allocation, a fixed pool of timers, time counted in whole *ticks*. A timer carries a 32-bit `id` chosen by the caller.

        typedef struct { ... } tw_t;     /* see include/timerwheel.h */

    ## Time and firing order

    * The wheel starts at tick 0 (`tw_now`). `tw_add(w, id, delay)` makes the timer expire at tick `now + delay`; it **fires** when the wheel is advanced to that tick or past it.
    * Time moves only in `tw_advance`, one tick at a time. At every tick, all timers expiring at that tick fire in the order they were scheduled (the order of the `tw_add` / `tw_reschedule` calls: first in, first out).
      Timers with different expiry ticks fire in order of their ticks.
    * A timer can be scheduled arbitrarily far ahead (more than one revolution of the wheel): `slots` only sets the internal hash size, never the maximum delay.

    ## API

    * `void tw_init(tw_t *w, unsigned slots)`: an empty wheel at tick 0 with `slots` hash slots (`1 <= slots <= TW_MAX_SLOTS` (32); a value outside this range is replaced by 8). The pool holds `TW_MAX_TIMERS` (16) timers.
    * `int tw_add(tw_t *w, uint32_t id, uint32_t delay)`: returns 0, or `TW_E_DELAY` (-1) when `delay == 0`, `TW_E_FULL` (-2) when the pool is full, `TW_E_DUP` (-3) when a pending timer already has this `id`. (Checked in this
      order: delay, duplicate, full.) Delays are 32-bit values and the expiry tick is a 64-bit number, so no delay can overflow.
    * `int tw_cancel(tw_t *w, uint32_t id)`: removes the pending timer; 1 if there was one, else 0.
    * `int tw_reschedule(tw_t *w, uint32_t id, uint32_t delay)`: moves a pending timer to expire at `now + delay` and puts it **behind** the timers already scheduled for that tick. Returns 0, `TW_E_DELAY` (-1) for `delay == 0`, or `TW_E_NONE` (-4) when
      there is no such timer (delay is checked first); a failing call changes nothing.
    * `size_t tw_advance(tw_t *w, uint32_t ticks, uint32_t *fired, size_t cap)`: advances by up to `ticks` ticks and stores the ids of the timers that fire, in firing order, in `fired` (room for `cap` ids); returns how many fired. A tick is never
      processed halfway: if the timers of the next tick do not all fit in the remaining room, the advance **stops before that tick** (the wheel's time is then the last fully processed tick). The caller can call again with more room. `fired` may be
      NULL when `cap` is 0. Fired timers leave the pool.
    * `uint64_t tw_now(const tw_t *w)`: the current tick. `size_t tw_pending(const tw_t *w)`: how many timers are scheduled.
    * `int tw_next(const tw_t *w, uint32_t *delta)`: when a timer is pending, stores the number of ticks until the earliest expiry (at least 1) in `*delta` and returns 1; otherwise returns 0 and leaves `*delta` alone.
    * `size_t tw_list(const tw_t *w, uint32_t *ids, size_t cap)`: the ids of the pending timers in the order in which they would fire, at most `cap` of them; returns how many were stored.
''')

