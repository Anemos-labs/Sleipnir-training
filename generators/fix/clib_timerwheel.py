F3 = dd(r'''
    #include "timerwheel.h"

    void tw_init(tw_t *w, unsigned slots) {
        int i;
        if (slots < 1 || slots > TW_MAX_SLOTS) slots = 8;
        w->slots = slots;
        w->now = 0;
        w->seq = 0;
        w->pending = 0;
        for (i = 0; i < TW_MAX_SLOTS; i++) {
            w->head[i] = -1;
            w->tail[i] = -1;
        }
        for (i = 0; i < TW_MAX_TIMERS; i++) {
            w->timers[i].used = 0;
            w->timers[i].next = -1;
        }
    }

    static int find(const tw_t *w, uint32_t id) {
        int i;
        for (i = 0; i < TW_MAX_TIMERS; i++) {
            if (w->timers[i].used && w->timers[i].id == id) return i;
        }
        return -1;
    }

    /* append timer t to the slot of its expiry tick */
    static void link_tail(tw_t *w, int t) {
        unsigned s = (unsigned)(w->timers[t].expire % w->slots);
        w->timers[t].next = -1;
        w->timers[t].seq = w->seq++;
        if (w->tail[s] < 0) w->head[s] = t;
        else w->timers[w->tail[s]].next = t;
        w->tail[s] = t;
    }

    static void unlink_timer(tw_t *w, int t) {
        unsigned s = (unsigned)(w->timers[t].expire % w->slots);
        int prev = -1, cur = w->head[s];
        while (cur >= 0 && cur != t) {
            prev = cur;
            cur = w->timers[cur].next;
        }
        if (cur < 0) return;
        if (prev < 0) w->head[s] = w->timers[t].next;
        else w->timers[prev].next = w->timers[t].next;
        if (w->tail[s] == t) w->tail[s] = prev;
        w->timers[t].next = -1;
    }

    int tw_add(tw_t *w, uint32_t id, uint32_t delay) {
        int t;
        if (delay == 0) return TW_E_DELAY;
        if (find(w, id) >= 0) return TW_E_DUP;
        for (t = 0; t < TW_MAX_TIMERS && w->timers[t].used; t++) {
        }
        if (t == TW_MAX_TIMERS) return TW_E_FULL;
        w->timers[t].used = 1;
        w->timers[t].id = id;
        w->timers[t].expire = w->now + delay;
        link_tail(w, t);
        w->pending++;
        return 0;
    }

    int tw_cancel(tw_t *w, uint32_t id) {
        int t = find(w, id);
        if (t < 0) return 0;
        unlink_timer(w, t);
        w->timers[t].used = 0;
        w->pending--;
        return 1;
    }

    int tw_reschedule(tw_t *w, uint32_t id, uint32_t delay) {
        int t;
        if (delay == 0) return TW_E_DELAY;
        t = find(w, id);
        if (t < 0) return TW_E_NONE;
        unlink_timer(w, t);
        w->timers[t].expire = w->now + delay;
        link_tail(w, t);
        return 0;
    }

    /* how many timers expire exactly at tick `at` */
    static size_t due_count(const tw_t *w, uint64_t at) {
        size_t n = 0;
        int cur = w->head[at % w->slots];
        while (cur >= 0) {
            if (w->timers[cur].expire == at) n++;
            cur = w->timers[cur].next;
        }
        return n;
    }

    size_t tw_advance(tw_t *w, uint32_t ticks, uint32_t *fired, size_t cap) {
        size_t count = 0;
        uint32_t step;
        for (step = 0; step < ticks; step++) {
            uint64_t at = w->now + 1;
            unsigned s = (unsigned)(at % w->slots);
            int cur, nxt;
            if (w->pending == 0) {
                w->now += ticks - step;
                break;
            }
            if (due_count(w, at) > cap - count) break;
            for (cur = w->head[s]; cur >= 0; cur = nxt) {
                nxt = w->timers[cur].next;
                if (w->timers[cur].expire == at) {
                    fired[count++] = w->timers[cur].id;
                    unlink_timer(w, cur);
                    w->timers[cur].used = 0;
                    w->pending--;
                }
            }
            w->now = at;
        }
        return count;
    }

    uint64_t tw_now(const tw_t *w) { return w->now; }

    size_t tw_pending(const tw_t *w) { return w->pending; }

    int tw_next(const tw_t *w, uint32_t *delta) {
        int i, any = 0;
        uint64_t best = 0;
        for (i = 0; i < TW_MAX_TIMERS; i++) {
            if (!w->timers[i].used) continue;
            if (!any || w->timers[i].expire < best) best = w->timers[i].expire;
            any = 1;
        }
        if (!any) return 0;
        *delta = (uint32_t)(best - w->now);
        return 1;
    }

    size_t tw_list(const tw_t *w, uint32_t *ids, size_t cap) {
        int order[TW_MAX_TIMERS];
        int n = 0, i, j;
        for (i = 0; i < TW_MAX_TIMERS; i++) {
            if (!w->timers[i].used) continue;
            for (j = n; j > 0; j--) {
                const tw_timer *a = &w->timers[order[j - 1]], *b = &w->timers[i];
                if (a->expire < b->expire || (a->expire == b->expire && a->seq < b->seq)) break;
                order[j] = order[j - 1];
            }
            order[j] = i;
            n++;
        }
        for (i = 0; i < n && (size_t)i < cap; i++) ids[i] = w->timers[order[i]].id;
        return (size_t)i;
    }
''')

