README1 = dd(r'''
    # replaywin

    A sliding window that decides whether a packet with a 16-bit sequence number is new, a duplicate, too old or implausibly far
    ahead. Sequence numbers wrap around: after `65535` comes `0`.

    ## State

        typedef struct { uint16_t top, base; uint32_t bitmap; uint32_t accepted; int started; } rw_t;

    * `top` is the highest sequence number accepted so far, in the wrap-around sense; `bitmap` has bit `i` set when the number
      `top - i` (mod 65536) has been accepted, for `i = 0..31` (so bit 0 is always set once a packet was accepted).
    * `accepted` counts the packets accepted. `base` is the oldest sequence number the window has seen (see `rw_missing`).

    ## Distances

    For a packet `seq` and the current `top`, let `diff = (uint16_t)(seq - top)` (arithmetic modulo 65536).

    * `diff == 0`: the packet repeats `top` (a duplicate).
    * `0 < diff < 0x8000`: the packet is **ahead** of `top` by `diff`.
    * `diff >= 0x8000`: the packet is **behind** `top` by `back = 65536 - diff` (`1..32768`).

    ## API

    * `void rw_init(rw_t *w)`: nothing seen yet (`started = 0`, everything else 0).
    * `int rw_check(const rw_t *w, uint16_t seq)` returns the verdict without changing anything:
      * `RW_NEW` (0) for the very first packet (nothing seen yet), whatever its number;
      * otherwise, for a packet ahead: `RW_FAR` when `diff > RW_MAX_JUMP` (1024), else `RW_NEW`;
      * for a packet behind: `RW_OLD` when `back >= 32` (it has left the window); otherwise `RW_DUP` if bit `back` of the bitmap is set
        and `RW_NEW` if it is clear;
      * `diff == 0` is `RW_DUP`.
    * `int rw_accept(rw_t *w, uint16_t seq)` does `rw_check` and, only for `RW_NEW`, records the packet and increments `accepted`:
      * the first packet sets `top = base = seq`, `bitmap = 1`;
      * a packet ahead by `diff` moves the window: the bitmap is shifted left by `diff` (it becomes 0 when `diff >= 32`), bit 0
        is set and `top = seq`; afterwards, when `top - base` (mod 65536) is greater than 31, `base` is moved to `top - 31`;
      * a packet behind sets bit `back`; when it is older than `base` (that is `(uint16_t)(seq - base) >= 0x8000`), `base` becomes `seq`.
      Returns the verdict. `RW_DUP`, `RW_OLD` and `RW_FAR` packets change nothing.
    * `int rw_missing(const rw_t *w)`: how many numbers between `base` and `top` (both included, never more than the 32 numbers of the
      window) have not been accepted; 0 when nothing has been seen. For `span = min(31, (uint16_t)(top - base))`, it is the number of
      clear bits among bits `0..span` of the bitmap.
    * `uint32_t rw_accepted(const rw_t *w)`: the `accepted` counter.
''')

