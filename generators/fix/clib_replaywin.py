F3 = dd(r'''
    #include "replaywin.h"

    void rw_init(rw_t *w) {
        w->top = 0;
        w->base = 0;
        w->bitmap = 0;
        w->accepted = 0;
        w->started = 0;
    }

    int rw_check(const rw_t *w, uint16_t seq) {
        uint16_t diff;
        unsigned back;
        if (!w->started) return RW_NEW;
        diff = (uint16_t)(seq - w->top);
        if (diff == 0) return RW_DUP;
        if (diff < 0x8000) return diff > RW_MAX_JUMP ? RW_FAR : RW_NEW;
        back = 65536u - diff;
        if (back >= 32) return RW_OLD;
        return (w->bitmap >> back) & 1u ? RW_DUP : RW_NEW;
    }

    int rw_accept(rw_t *w, uint16_t seq) {
        int verdict = rw_check(w, seq);
        uint16_t diff;
        if (verdict != RW_NEW) return verdict;
        if (!w->started) {
            w->started = 1;
            w->top = w->base = seq;
            w->bitmap = 1;
        } else {
            diff = (uint16_t)(seq - w->top);
            if (diff < 0x8000) {
                w->bitmap = diff >= 32 ? 0 : w->bitmap << diff;
                w->bitmap |= 1u;
                w->top = seq;
                if ((uint16_t)(w->top - w->base) > 31) w->base = (uint16_t)(w->top - 31);
            } else {
                w->bitmap |= 1u << (65536u - diff);
                if ((uint16_t)(seq - w->base) >= 0x8000) w->base = seq;
            }
        }
        w->accepted++;
        return RW_NEW;
    }

    int rw_missing(const rw_t *w) {
        int span, i, missing = 0;
        if (!w->started) return 0;
        span = (uint16_t)(w->top - w->base);
        if (span > 31) span = 31;
        for (i = 0; i <= span; i++) {
            if (!((w->bitmap >> i) & 1u)) missing++;
        }
        return missing;
    }

    uint32_t rw_accepted(const rw_t *w) { return w->accepted; }
''')

