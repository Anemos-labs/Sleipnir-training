README1 = dd(r'''
    # lotbook

    A batch ledger for a pharmacy's stock. Every delivery is a *batch* with an id, an expiry day, a quantity and a unit cost (in
    cents). Days are plain integers (a day number); a batch is **usable on its expiry day** and expired from the day after
    (`expiry < today` means expired). Medicine is issued **first-expired-first-out** (FEFO): the batch with the earliest expiry goes first.

        struct Batch { std::string id; int expiry; int qty; long unit_cost; };
        struct Pick  { std::string batch; int expiry; int qty; long unit_cost; };

    `StockError` (a `std::runtime_error`) is thrown when a request cannot be met; `std::invalid_argument` for malformed arguments. A call
    that throws leaves the ledger unchanged.

    ## `class StockBook`

    * `void receive(const std::string &id, int qty, long unit_cost, int expiry)` records a delivery. `qty <= 0`, `unit_cost < 0`
      or an empty `id` is `std::invalid_argument`. When a batch with that `id` already exists, its `unit_cost` and `expiry` must be
      the same (else `std::invalid_argument`) and the quantity is added; otherwise a new batch is created.
    * `std::vector<Batch> batches() const` lists all batches (expired ones too), ordered by expiry, then by id (plain string order).
    * `int on_hand(int today) const`: total quantity of the batches that are not expired on `today`.
    * `long value(int today) const`: the sum of `qty * unit_cost` over those batches.
    * `std::optional<int> next_expiry(int today) const`: the earliest expiry day that is not before `today`, if any batch is usable.
    * `std::vector<std::string> expiring_within(int today, int days) const`: ids of the batches with `today <= expiry <= today + days`, in
      ledger order (expiry, id); empty when `days < 0`.
    * `std::vector<Pick> issue(int qty, int today)` takes `qty` units from the usable batches in FEFO order (expiry, then id). One `Pick`
      per batch touched, in that order, with the quantity taken from it. `qty <= 0` is `std::invalid_argument`; when the usable stock is
      below `qty` it throws `StockError` and changes nothing. A batch whose quantity reaches 0 disappears from the ledger. Expired batches are
      never touched.
    * `void give_back(const Pick &p)` returns units to the batch they came from: `p.qty <= 0` is `std::invalid_argument`; when the batch
      still exists its `unit_cost` and `expiry` must match the pick (`std::invalid_argument` otherwise) and the quantity is added; when it
      was emptied it is recreated from the pick.
    * `std::vector<Batch> expire(int today)` removes every expired batch (`expiry < today`) and returns them in ledger order.

    `long cost_of(const std::vector<Pick> &picks)` is the sum of `qty * unit_cost` over the picks.
''')

