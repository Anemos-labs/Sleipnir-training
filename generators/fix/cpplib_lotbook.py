F3 = dd(r'''
    #include "lotbook.hpp"

    namespace lotbook {

    static bool before(const Batch &a, const Batch &b) {
        if (a.expiry != b.expiry) return a.expiry < b.expiry;
        return a.id < b.id;
    }

    void StockBook::insert_sorted(const Batch &b) {
        size_t i = 0;
        while (i < batches_.size() && before(batches_[i], b)) i++;
        batches_.insert(batches_.begin() + static_cast<long>(i), b);
    }

    int StockBook::find(const std::string &id) const {
        for (size_t i = 0; i < batches_.size(); i++) {
            if (batches_[i].id == id) return static_cast<int>(i);
        }
        return -1;
    }

    void StockBook::receive(const std::string &id, int qty, long unit_cost, int expiry) {
        if (qty <= 0 || unit_cost < 0 || id.empty()) throw std::invalid_argument("bad delivery");
        int at = find(id);
        if (at >= 0) {
            Batch &b = batches_[static_cast<size_t>(at)];
            if (b.unit_cost != unit_cost || b.expiry != expiry) throw std::invalid_argument("batch exists with other terms");
            b.qty += qty;
            return;
        }
        insert_sorted(Batch{id, expiry, qty, unit_cost});
    }

    std::vector<Batch> StockBook::batches() const { return batches_; }

    int StockBook::on_hand(int today) const {
        int total = 0;
        for (const Batch &b : batches_) {
            if (b.expiry >= today) total += b.qty;
        }
        return total;
    }

    long StockBook::value(int today) const {
        long total = 0;
        for (const Batch &b : batches_) {
            if (b.expiry >= today) total += static_cast<long>(b.qty) * b.unit_cost;
        }
        return total;
    }

    std::optional<int> StockBook::next_expiry(int today) const {
        for (const Batch &b : batches_) {
            if (b.expiry >= today) return b.expiry;
        }
        return std::nullopt;
    }

    std::vector<std::string> StockBook::expiring_within(int today, int days) const {
        std::vector<std::string> out;
        if (days < 0) return out;
        for (const Batch &b : batches_) {
            if (b.expiry >= today && b.expiry <= today + days) out.push_back(b.id);
        }
        return out;
    }

    std::vector<Pick> StockBook::issue(int qty, int today) {
        if (qty <= 0) throw std::invalid_argument("qty must be positive");
        if (on_hand(today) < qty) throw StockError("insufficient stock");
        std::vector<Pick> picks;
        int left = qty;
        for (size_t i = 0; i < batches_.size() && left > 0;) {
            Batch &b = batches_[i];
            if (b.expiry < today) {
                i++;
                continue;
            }
            int take = b.qty < left ? b.qty : left;
            picks.push_back(Pick{b.id, b.expiry, take, b.unit_cost});
            b.qty -= take;
            left -= take;
            if (b.qty == 0) {
                batches_.erase(batches_.begin() + static_cast<long>(i));
            } else {
                i++;
            }
        }
        return picks;
    }

    void StockBook::give_back(const Pick &p) {
        if (p.qty <= 0) throw std::invalid_argument("bad return");
        int at = find(p.batch);
        if (at >= 0) {
            Batch &b = batches_[static_cast<size_t>(at)];
            if (b.unit_cost != p.unit_cost || b.expiry != p.expiry) throw std::invalid_argument("return does not match the batch");
            b.qty += p.qty;
            return;
        }
        insert_sorted(Batch{p.batch, p.expiry, p.qty, p.unit_cost});
    }

    std::vector<Batch> StockBook::expire(int today) {
        std::vector<Batch> gone, keep;
        for (const Batch &b : batches_) {
            if (b.expiry < today) gone.push_back(b);
            else keep.push_back(b);
        }
        batches_ = keep;
        return gone;
    }

    long cost_of(const std::vector<Pick> &picks) {
        long total = 0;
        for (const Pick &p : picks) total += static_cast<long>(p.qty) * p.unit_cost;
        return total;
    }

    }  // namespace lotbook
''')

