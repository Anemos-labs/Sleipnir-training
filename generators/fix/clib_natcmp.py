            CHECK_STR(s1[2], "a100");
            CHECK_STR(s1[3], "b9");
            CHECK_STR(s1[4], "b10");
            nc_sort(s1, 0, 0);
            nc_sort(s1, 1, 0);
            CHECK_STR(s1[0], "B1");
