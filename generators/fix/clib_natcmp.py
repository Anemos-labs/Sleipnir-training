        CHECK_INT(nc_is_sorted(b, 3, 0), 0);
        CHECK_INT(nc_is_sorted(a, 0, 0), 1);
        CHECK_INT(nc_is_sorted(a, 1, 0), 1);
        CHECK_INT(nc_is_sorted(b, 1, 0), 1);
        CHECK_INT(nc_is_sorted(b, 2, 0), 1);
        CHECK_INT(nc_is_sorted(c, 2, 0), 0);
        CHECK_INT(nc_is_sorted(d, 2, 0), 1);
        CHECK_INT(nc_is_sorted(c, 2, NC_FOLD), 1);
        CHECK_INT(nc_is_sorted(d, 2, NC_FOLD), 1);
        CHECK_INT(nc_is_sorted(e, 2, 0), 0);
