README1 = dd(r'''
    # natcmp

    Natural ordering for file names: `plate_2` sorts before `plate_10`. Strings are given with explicit lengths (they need not be NUL-terminated, embedded NUL bytes are ordinary bytes) and are never read beyond their length.

    ## `int nc_compare(const char *a, size_t na, const char *b, size_t nb, int flags)`

    Returns -1, 0 or 1. The strings are cut into **digit runs** (maximal runs of ASCII `0`-`9`) and **other bytes**, and compared from the left, piece by piece:

    * two digit runs are compared by their **numeric value**, whatever their length (they may have hundreds of digits and are never converted to a machine integer): leading zeros are ignored, then the run with fewer digits is smaller, then the
      digits are compared from the left; the first difference decides;
    * a digit run is **smaller than** any other byte (so `a1` < `a_` and `a1` < `ab`; digits sort before everything else, the digit `0` included);
    * two other bytes are compared as unsigned byte values (so `B` < `a`); with the flag `NC_FOLD` the ASCII letters `A-Z` are first turned into `a-z` (other bytes, including non-ASCII ones, are unchanged);
    * when one string ends before the other (and everything before was equal), the shorter one is smaller.

    If the whole comparison is equal this way, the strings are ordered by their leading zeros: looking at the digit runs from the left, the first pair of runs that have a **different number of leading zeros** decides, and the run with *fewer* leading zeros
    comes first (`a1` < `a01` < `a001`; for `x007y1` and `x7y01` the first run decides). A run of only zeros such as `000` has all its digits as leading zeros, so `0` < `00` < `000`, and `0` and `00` are numerically equal.
    If that does not separate them either, the result is 0 (with `NC_FOLD` that includes strings that differ only by ASCII case).

    `NC_FOLD` is 1; `0` means no flags.

    ## `void nc_sort(const char **names, size_t count, int flags)`

    Sorts an array of NUL-terminated strings in place with `nc_compare` (lengths from `strlen`), ascending and **stably**: strings that compare equal keep their order.

    ## `int nc_is_sorted(const char *const *names, size_t count, int flags)`

    1 when no string compares smaller than the one before it, else 0 (0 or 1 strings are sorted).
''')

