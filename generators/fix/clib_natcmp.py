F3 = dd(r'''
    #include "natcmp.h"

    #include <string.h>

    static int is_digit(unsigned char c) { return c >= '0' && c <= '9'; }

    static int fold(unsigned char c, int flags) {
        if ((flags & NC_FOLD) && c >= 'A' && c <= 'Z') return c - 'A' + 'a';
        return c;
    }

    /* length of the digit run starting at s[i] */
    static size_t run_len(const char *s, size_t n, size_t i) {
        size_t j = i;
        while (j < n && is_digit((unsigned char)s[j])) j++;
        return j - i;
    }

    int nc_compare(const char *a, size_t na, const char *b, size_t nb, int flags) {
        size_t i = 0, j = 0;
        int zero_order = 0;
        while (i < na && j < nb) {
            unsigned char ca = (unsigned char)a[i], cb = (unsigned char)b[j];
            if (is_digit(ca) && is_digit(cb)) {
                size_t la = run_len(a, na, i), lb = run_len(b, nb, j);
                size_t za = 0, zb = 0, k;
                while (za < la && a[i + za] == '0') za++;
                while (zb < lb && b[j + zb] == '0') zb++;
                if (za == la || zb == lb) {
                    /* a run of only zeros has the value 0 */
                    if (za != la) return 1;
                    if (zb != lb) return -1;
                } else {
                    if (la - za != lb - zb) return la - za < lb - zb ? -1 : 1;
                    for (k = 0; k < la - za; k++) {
                        if (a[i + za + k] != b[j + zb + k]) return a[i + za + k] < b[j + zb + k] ? -1 : 1;
                    }
                }
                if (zero_order == 0 && za != zb) zero_order = za < zb ? -1 : 1;
                i += la;
                j += lb;
                continue;
            }
            if (is_digit(ca)) return -1;
            if (is_digit(cb)) return 1;
            {
                int fa = fold(ca, flags), fb = fold(cb, flags);
                if (fa != fb) return fa < fb ? -1 : 1;
            }
            i++;
            j++;
        }
        if (i < na) return 1;
        if (j < nb) return -1;
        return zero_order;
    }

    void nc_sort(const char **names, size_t count, int flags) {
        size_t i, k;
        for (i = 1; i < count; i++) {
            const char *cur = names[i];
            size_t len = strlen(cur);
            for (k = i; k > 0 && nc_compare(names[k - 1], strlen(names[k - 1]), cur, len, flags) > 0; k--) names[k] = names[k - 1];
            names[k] = cur;
        }
    }

    int nc_is_sorted(const char *const *names, size_t count, int flags) {
        size_t i;
        for (i = 1; i < count; i++) {
            if (nc_compare(names[i - 1], strlen(names[i - 1]), names[i], strlen(names[i]), flags) > 0) return 0;
        }
        return 1;
    }
''')

