F3 = dd(r'''
    #include "cellfit.h"

    #include <string.h>

    int cf_decode(const char *str, size_t n, uint32_t *cp) {
        const unsigned char *s = (const unsigned char *)str;
        unsigned c;
        size_t need, i;
        uint32_t v, min;
        if (n == 0) return 0;
        c = s[0];
        if (c < 0x80) {
            *cp = c;
            return 1;
        }
        if (c >= 0xC2 && c <= 0xDF) {
            need = 1;
            v = c & 0x1F;
            min = 0x80;
        } else if (c >= 0xE0 && c <= 0xEF) {
            need = 2;
            v = c & 0x0F;
            min = 0x800;
        } else if (c >= 0xF0 && c <= 0xF4) {
            need = 3;
            v = c & 0x07;
            min = 0x10000;
        } else {
            goto invalid;
        }
        if (n < need + 1) goto invalid;
        for (i = 1; i <= need; i++) {
            if ((s[i] & 0xC0) != 0x80) goto invalid;
            v = (v << 6) | (s[i] & 0x3F);
        }
        if (v < min || v > 0x10FFFF || (v >= 0xD800 && v <= 0xDFFF)) goto invalid;
        *cp = v;
        return (int)need + 1;
    invalid:
        *cp = 0xFFFD;
        return 1;
    }

    int cf_cp_width(uint32_t c) {
        if (c < 0x20 || (c >= 0x7F && c <= 0x9F)) return 0;
        if ((c >= 0x0300 && c <= 0x036F) || (c >= 0x200B && c <= 0x200D)) return 0;
        if ((c >= 0x1100 && c <= 0x115F) || (c >= 0x2E80 && c <= 0xA4CF && c != 0x303F) || (c >= 0xAC00 && c <= 0xD7A3) ||
            (c >= 0xF900 && c <= 0xFAFF) || (c >= 0xFE30 && c <= 0xFE6F) || (c >= 0xFF00 && c <= 0xFF60) ||
            (c >= 0xFFE0 && c <= 0xFFE6) || (c >= 0x1F300 && c <= 0x1F64F) || (c >= 0x1F900 && c <= 0x1F9FF) ||
            (c >= 0x20000 && c <= 0x3FFFD))
            return 2;
        return 1;
    }

    /* width of the character at s: invalid bytes are 1 column */
    static int char_width(const char *s, size_t n, size_t *len) {
        uint32_t cp;
        int l = cf_decode(s, n, &cp);
        *len = (size_t)l;
        if (l == 1 && cp == 0xFFFD) return 1;
        return cf_cp_width(cp);
    }

    int cf_width(const char *s, size_t n) {
        size_t i = 0, len;
        int w = 0;
        while (i < n) {
            w += char_width(s + i, n - i, &len);
            i += len;
        }
        return w;
    }

    int cf_fit(char *dst, size_t cap, const char *s, size_t n, int width, int ellipsis) {
        size_t i = 0, len, out = 0;
        int budget_w, cols = 0;
        long budget_b;
        if (cap == 0) return -1;
        if (width < 0) width = 0;
        if (cf_width(s, n) <= width && n <= cap - 1) {
            memcpy(dst, s, n);
            dst[n] = '\0';
            return (int)n;
        }
        budget_w = width;
        budget_b = (long)cap - 1;
        if (ellipsis && width >= 1 && cap >= 4) {
            budget_w -= 1;
            budget_b -= 3;
        } else {
            ellipsis = 0;
        }
        while (i < n) {
            int w = char_width(s + i, n - i, &len);
            if (cols + w > budget_w || (long)(out + len) > budget_b) break;
            memcpy(dst + out, s + i, len);
            out += len;
            cols += w;
            i += len;
        }
        if (ellipsis) {
            memcpy(dst + out, "\xE2\x80\xA6", 3);
            out += 3;
        }
        dst[out] = '\0';
        return (int)out;
    }

    int cf_pad(char *dst, size_t cap, const char *s, size_t n, int width, int align) {
        int len, w, pad, before, after;
        if (cap == 0 || width < 0) return -1;
        len = cf_fit(dst, cap, s, n, width, 1);
        w = cf_width(dst, (size_t)len);
        pad = width - w;
        if ((size_t)len + (size_t)pad + 1 > cap) return -1;
        before = align == CF_RIGHT ? pad : (align == CF_CENTER ? pad / 2 : 0);
        after = pad - before;
        memmove(dst + before, dst, (size_t)len);
        memset(dst, ' ', (size_t)before);
        memset(dst + before + len, ' ', (size_t)after);
        dst[before + len + after] = '\0';
        return before + len + after;
    }
''')

