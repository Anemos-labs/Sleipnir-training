README1 = dd(r'''
    # cellfit

    Helpers to fit UTF-8 text into fixed-width terminal table cells. Strings are given as a pointer and a length (they need
    not be NUL-terminated and are never read beyond the length).

    ## Decoding

    `int cf_decode(const char *s, size_t n, uint32_t *cp)` decodes one character from the front of `s` (`n` bytes available)
    and returns the number of bytes it uses; it returns 0 when `n == 0`. Decoding is **strict**:

    * valid sequences are 1 to 4 bytes: lead byte `00..7F`; `C2..DF` + 1 continuation; `E0..EF` + 2; `F0..F4` + 3, where a
      continuation byte is `80..BF`;
    * the decoded value must use the shortest form (no overlong encodings such as `C0 80` or `E0 80 80`), must not be a
      surrogate (`U+D800..U+DFFF`) and must not exceed `U+10FFFF`;
    * anything else (a stray continuation byte, a lead byte whose continuations are missing, wrong or cut off by `n`, a byte `C0`,
      `C1` or `F5..FF`, an overlong form, a surrogate, a value too large) is **one invalid byte**: the function returns 1 and sets
      `*cp = 0xFFFD`. The bytes after it are then decoded on their own.

    (A genuine `U+FFFD` is the three bytes `EF BF BD`; it returns 3.)

    ## Display width

    `int cf_cp_width(uint32_t cp)` is the number of terminal columns of a code point:

    * **0** for controls `U+0000..U+001F` and `U+007F..U+009F`, for combining marks `U+0300..U+036F` and for zero-width
      `U+200B..U+200D`;
    * **2** for `U+1100..U+115F`, `U+2E80..U+A4CF` except `U+303F`, `U+AC00..U+D7A3`, `U+F900..U+FAFF`, `U+FE30..U+FE6F`,
      `U+FF00..U+FF60`, `U+FFE0..U+FFE6`, `U+1F300..U+1F64F`, `U+1F900..U+1F9FF` and `U+20000..U+3FFFD`;
    * **1** for everything else.

    `int cf_width(const char *s, size_t n)` is the total width of the string. An invalid byte counts as 1 column.

    ## Fitting

    `int cf_fit(char *dst, size_t cap, const char *s, size_t n, int width, int ellipsis)` writes `s` into `dst` (at most `cap`
    bytes including the NUL) so that it is at most `width` columns wide, and returns its length in bytes. It returns -1, writing
    nothing, when `cap == 0`. A negative `width` counts as 0.

    1. If the whole string is at most `width` columns **and** at most `cap - 1` bytes, it is copied unchanged.
    2. Otherwise it is *truncated*: whole characters (an invalid byte counts as a character of 1 byte and 1 column, copied
       unchanged) are taken from the front for as long as both the column budget and the byte budget hold. A character
       that does not fit ends the copy even if a later, narrower one would; zero-width characters directly before that point are
       kept. With `ellipsis != 0` the budgets first shrink to make room for the ellipsis `U+2026` (bytes `E2 80 A6`, 1 column,
       3 bytes): column budget `width - 1`, byte budget `cap - 1 - 3`, and the ellipsis is appended after the copied
       characters. If the ellipsis itself does not fit (`width < 1` or `cap < 4`), no ellipsis is added and the budgets stay as
       they were. (The result may then be empty.)

    `int cf_pad(char *dst, size_t cap, const char *s, size_t n, int width, int align)` produces exactly `width` columns
    (for `width >= 0`): the text is fitted as above with an ellipsis and with the byte capacity `cap`, then padded with ASCII spaces
    to the width: `CF_LEFT` puts the spaces after the text, `CF_RIGHT` before it, `CF_CENTER` puts `pad / 2` (rounded down) spaces before
    and the rest after. Returns the length in bytes, or -1 (leaving `dst` unspecified but never writing beyond `cap`) when `cap == 0`, `width < 0` or the padded text
    and its NUL would not fit in `cap` bytes.
''')

